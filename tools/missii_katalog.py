def arena(m):
    if m.get('survive'): return ('оборона', 'бой', 'продержаться ' + str(m['survive']) + ' с', 'точка пала')
    if m.get('docs'): return ('сбор', 'бой', f"найти {m['docs']} × «{m.get('docName','')}» у охраны", 'убит')
    if m.get('boss'): return ('перестрелка с боссом', 'босс', 'волны, затем босс', 'убит')
    return ('перестрелка', 'бой', 'волны пешком', 'убит')

def xz(m):
    st = m.get('start')
    if isinstance(st, list) and len(st) >= 2 and all(isinstance(v, (int, float)) for v in st[:2]): return st[0], st[1]
    a = m.get('arena')
    if isinstance(a, list) and len(a) == 2: return a[0], a[1]
    s = m.get('steps')
    if isinstance(s, list) and s and isinstance(s[0], dict) and isinstance(s[0].get('at'), list): return s[0]['at'][0], s[0]['at'][1]
    return '', ''

