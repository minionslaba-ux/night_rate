export const msk = (d = new Date()) => new Date(d.getTime() + 3 * 3600e3);
export const weekNo = (d = new Date()) => Math.floor((msk(d).getTime() / 864e5 + 3) / 7);
const pick = <T>(a: T[], k: number) => a[((k % a.length) + a.length) % a.length];

// пост на сегодня; stats — функция, которая считает итоги недели (только для воскресенья)
export async function dailyPost(stats: () => Promise<string>) {
  const d = msk(), wd = d.getUTCDay(), w = weekNo();
  if (wd === 0) return await stats();
  if (wd === 1) return pick(FEATURES, w);
  if (wd === 2) { const [n, nick, age, bio, perk] = pick(DRIVERS, w); return `🚕 <b>Водитель недели: ${n} «${nick}», ${age}</b>\n\n${bio}\n\n⭐ ${perk}`; }
  if (wd === 3) return pick(TIPS, w * 2);
  if (wd === 4) return pick(PLACES, w);
  if (wd === 5) return pick(FRIDAY, w);
  return pick(TIPS, w * 2 + 1);
}
